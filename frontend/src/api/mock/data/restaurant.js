/** 4 张实拍图按 seed 取 3 张，避免同一屏里所有餐厅主图一样 */
function imagesFor(seed) {
  const n = 4
  const start = seed % n
  return [0, 1, 2].map((i) => `/pictures/lun_bo_tu_${((start + i) % n) + 1}.png`).join(',')
}

export const RESTAURANTS = ROWS.map(([name, dish, hours, cost, address, phone, intro], i) => {
  const id = 91 + i
  const h = hashSeed(`restaurant:${id}`)
  const p = (n) => String(n).padStart(2, '0')
  const d = new Date(Date.now() - (h % 300) * 86400000)
  const addTime = `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(h % 24)}:${p((h >> 3) % 60)}:00`

  return {
    id,
    restaurantName: name,
    restaurantImage: imagesFor(id),
    signatureDish: dish,
    businessHours: hours,
    avgCost: cost,
    restaurantAddress: address,
    contactPhone: phone,
    restaurantIntro: intro,
    thumbsUpNum: 50 + (h % 480),
    crazilyNum: 15 + ((h >> 4) % 190),
    clickTime: addTime,
    clickNum: 60 + ((h >> 8) % 500),
    discussNum: 4 + ((h >> 12) % 52),
    storeUpNum: 25 + ((h >> 16) % 240),
    addTime,
  }
})

