/** 从 4 张本地实拍图里按 seed 取 3 张，详情页的画廊因此有三张可切换的缩略图 */
function imagesFor(seed) {
  const n = 4
  const start = seed % n
  return [0, 1, 2].map((i) => `/pictures/lun_bo_tu_${((start + i) % n) + 1}.png`).join(',')
}

/** 热度三项按 id 造，稳定且量级可信。评论数不在这里造 —— 它等于实际生成的评论条数 */
function heatFor(id) {
  const h = hashSeed(`attraction-heat:${id}`)
  return {
    thumbsUpNum: 60 + (h % 420),
    crazilyNum: 20 + ((h >> 4) % 180),
    storeUpNum: 30 + ((h >> 8) % 260),
  }
}

/** 时间散布在最近一年内 */
function addTimeFor(id) {
  const h = hashSeed(`attraction-time:${id}`)
  const daysAgo = h % 330
  const d = new Date(Date.now() - daysAgo * 86400000)
  const p = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(h % 24)}:${p((h >> 3) % 60)}:00`
}

